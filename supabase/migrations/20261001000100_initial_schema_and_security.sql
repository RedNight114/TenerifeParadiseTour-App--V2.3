-- Initial schema for the existing TenerifeParadise Tours application.
-- The organization boundary is deliberately added in the next product phase.

create extension if not exists pgcrypto;

create table if not exists public.app_admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name_es text not null,
  name_en text not null,
  name_de text not null,
  description_es text,
  description_en text,
  description_de text,
  icon text,
  color text not null default '#3B82F6',
  active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.excursions (
  id bigint generated by default as identity primary key,
  name_es text not null,
  name_en text not null,
  name_de text not null,
  short_description_es text not null default '',
  short_description_en text not null default '',
  short_description_de text not null default '',
  description_es text not null default '',
  description_en text not null default '',
  description_de text not null default '',
  price numeric(10,2) not null check (price >= 0),
  price_max numeric(10,2) check (price_max is null or price_max >= price),
  children_price numeric(10,2) check (children_price is null or children_price >= 0),
  children_age_range text,
  duration text not null default '',
  category text not null,
  image_url text not null default '',
  gallery_images text[] not null default '{}',
  featured boolean not null default false,
  rating numeric(3,2) check (rating is null or rating between 0 and 5),
  included_services text[] not null default '{}',
  not_included_services text[] not null default '{}',
  difficulty_level text,
  start_time time,
  end_time time,
  meeting_point text,
  what_to_bring text,
  cancellation_policy text,
  age_restrictions text,
  available_months text[] not null default '{}',
  special_notes text,
  requirements text,
  faqs jsonb not null default '[]'::jsonb check (jsonb_typeof(faqs) = 'array'),
  max_people integer check (max_people is null or max_people > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.predefined_services (
  id bigint generated by default as identity primary key,
  name_es text not null,
  name_en text not null,
  name_de text not null,
  category text not null check (category in ('included', 'not_included')),
  icon text,
  created_at timestamptz not null default now()
);

create table if not exists public.bookings (
  id bigint generated by default as identity primary key,
  excursion_id bigint not null references public.excursions(id) on delete restrict,
  customer_name text not null,
  email text not null,
  phone text not null default '',
  preferred_date date not null,
  number_of_people integer not null check (number_of_people > 0),
  special_requests text,
  language text not null default 'es' check (language in ('es', 'en', 'de', 'fr', 'ru', 'zh')),
  created_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  message text not null,
  language text not null default 'es' check (language in ('es', 'en', 'de', 'fr', 'ru', 'zh')),
  created_at timestamptz not null default now()
);

create index if not exists excursions_featured_created_idx on public.excursions (featured desc, created_at desc);
create index if not exists excursions_category_idx on public.excursions (category);
create index if not exists bookings_created_idx on public.bookings (created_at desc);
create index if not exists bookings_excursion_date_idx on public.bookings (excursion_id, preferred_date);
create index if not exists contacts_created_idx on public.contacts (created_at desc);

create or replace function public.touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists categories_touch_updated_at on public.categories;
create trigger categories_touch_updated_at before update on public.categories
for each row execute function public.touch_updated_at();

drop trigger if exists excursions_touch_updated_at on public.excursions;
create trigger excursions_touch_updated_at before update on public.excursions
for each row execute function public.touch_updated_at();

alter table public.app_admins enable row level security;
