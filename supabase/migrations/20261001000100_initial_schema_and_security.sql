-- Remove legacy permissive policies before installing the allowlist below.
do $$
declare
  existing_policy record;
begin
  for existing_policy in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename = any(array['app_admins', 'categories', 'excursions', 'predefined_services', 'bookings', 'contacts'])
  loop
    execute format('drop policy %I on %I.%I', existing_policy.policyname, existing_policy.schemaname, existing_policy.tablename);
  end loop;
end;
$$;

drop policy if exists "admins can read their own grant" on public.app_admins;
create policy "admins can read their own grant" on public.app_admins
for select to authenticated using (user_id = (select auth.uid()));

drop policy if exists "public can read active categories" on public.categories;
create policy "public can read active categories" on public.categories
for select to anon, authenticated using (active or exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
));
drop policy if exists "admins manage categories" on public.categories;
create policy "admins manage categories" on public.categories
for all to authenticated using (exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
)) with check (exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
));

drop policy if exists "public can read excursions" on public.excursions;
create policy "public can read excursions" on public.excursions
for select to anon, authenticated using (true);
drop policy if exists "admins manage excursions" on public.excursions;
create policy "admins manage excursions" on public.excursions
for all to authenticated using (exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
)) with check (exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
));

drop policy if exists "public can read predefined services" on public.predefined_services;
create policy "public can read predefined services" on public.predefined_services
for select to anon, authenticated using (true);
drop policy if exists "admins manage predefined services" on public.predefined_services;
create policy "admins manage predefined services" on public.predefined_services
for all to authenticated using (exists (
  select 1 from public.app_admins where user_id = (select auth.uid())
